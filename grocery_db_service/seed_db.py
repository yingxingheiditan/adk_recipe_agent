def seed():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    c.execute("DROP TABLE IF EXISTS grocery_products")
    c.execute("""
        CREATE TABLE grocery_products (
            sku TEXT PRIMARY KEY,
            product_name TEXT NOT NULL,
            brand TEXT NOT NULL,
            ingredient_category TEXT NOT NULL,
            search_keywords TEXT NOT NULL,
            pack_size TEXT NOT NULL,
            price_sgd REAL NOT NULL,
            promo_price_sgd REAL,
            unit_price_display TEXT,
            dietary_tags TEXT,
            in_stock INTEGER NOT NULL,
            image_url TEXT NOT NULL,
            product_url TEXT NOT NULL
        )
    """)
    for p in PRODUCTS:
        c.execute("""
            INSERT INTO grocery_products (
                sku, product_name, brand, ingredient_category, search_keywords,
                pack_size, price_sgd, promo_price_sgd, unit_price_display,
                dietary_tags, in_stock, image_url, product_url
            ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """, (
            p["sku"], p["product_name"], p["brand"], p["ingredient_category"],
            p["search_keywords"], p["pack_size"], p["price_sgd"],
            p["promo_price_sgd"], p["unit_price_display"], p["dietary_tags"],
            1 if p["in_stock"] else 0, p["image_url"], p["product_url"]
        ))
    conn.commit()
    conn.close()
    print(f"Successfully seeded {len(PRODUCTS)} FreshMarket Singapore products into {DB_PATH}")

if __name__ == "__main__":
    seed()
